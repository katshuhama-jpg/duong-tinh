  list.map((v) => ({
    ...base,
    id: `${base.id}_${v.suf}`,
    when: { ...base.when, flags: [...(base.when?.flags ?? []), ...(v.flags ?? [])], not: [...(base.when?.not ?? []), ...(v.not ?? [])] },
  }));

